/// ── Smart Messaging Engine ──
///
/// Ported from spec section 3 ("ثالثاً: تطوير الرسائل الذكية"). The
/// goal stated there is explicit: *"لا أريد رسائل مكررة. أريد آلاف
/// الرسائل المختلفة مع تنوع كبير."* A fixed string per situation (the
/// old `generateSmartNotification` behaviour) can't deliver that, so
/// instead of one string per case this composes each message from four
/// independently-varying sentence pools (opener → observation →
/// interpretation/support → suggestion). Every pool sentence is a
/// complete, grammatically correct standalone sentence, so any
/// combination reads naturally — no slot-filling inside a sentence
/// that could break Arabic agreement.
///
/// With 6-10 variants per slot × 4 slots × 9 categories, the realistic
/// combination space is in the tens of thousands. Recency is enforced
/// on top of that via [avoidRepeats]: the caller keeps a short rolling
/// history of text hashes (persisted on `BehaviorProfileEntity
/// .recentMessageHashes`) and this engine retries a handful of times
/// before giving up and accepting a near-repeat, so the same day never
/// shows the same exact sentence twice.
///
/// 100% local, pure Dart, no network, no external AI.
class MessageEngine {
  final Random _rng;
  MessageEngine({Random? random}) : _rng = random ?? Random();

  static const int _maxRetries = 6;

  /// Compose a message for [category], filling any `{placeholder}`
  /// tokens in [params] into the chosen sentences. [recentHashes] is
  /// the caller's short history (most-recent last) used to dodge
  /// immediate repeats; pass an empty list if not tracking yet.
  GeneratedMessage compose(
    MessageCategory category, {
    Map<String, String> params = const {},
    List<String> recentHashes = const [],
  }) {
    final pools = _pools[category]!;
    final icons = _icons[category]!;

    String candidateText = "";
    String candidateIcon = icons.first;
    for (var attempt = 0; attempt < _maxRetries; attempt++) {
      final opener = _pick(pools.openers);
      final observation = _pick(pools.observations);
      final support = _pick(pools.supports);
      final suggestion = _pick(pools.suggestions);
      candidateIcon = _pick(icons);

      final ordered = pools.suggestionFirst
          ? [opener, suggestion, observation, support]
          : [opener, observation, support, suggestion];
      candidateText = _fill(ordered.where((s) => s.isNotEmpty).join(" "), params);

      final h = candidateText.hashCode.toString();
      if (!recentHashes.contains(h)) break;
    }

    return GeneratedMessage(icon: candidateIcon, text: candidateText, category: category);
  }

  /// Returns the hash string to append to a caller-side history list
  /// (cap it at ~40-60 entries and drop the oldest).
  String hashOf(GeneratedMessage m) => m.text.hashCode.toString();

  String _pick(List<String> pool) => pool[_rng.nextInt(pool.length)];

  String _fill(String template, Map<String, String> params) {
    var out = template;
    for (final e in params.entries) {
      out = out.replaceAll("{${e.key}}", e.value);
    }
    return out;
  }

